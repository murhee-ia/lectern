CREATE OR REPLACE FUNCTION prevent_admin_membership_delete() RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
  BEGIN
    IF old.role = 'admin' AND EXISTS (
      SELECT 1 FROM memberships
      WHERE organization_id = old.organization_id
        AND user_id <> old.user_id
    ) THEN
      RAISE EXCEPTION 'Cannot delete an organization''s Admin membership directly while other members exist. Hand off the Admin role first';
    END IF;
    RETURN old;
  END;
$$;

COMMENT ON FUNCTION prevent_admin_membership_delete() IS 'Defense-in-depth: blocks direct deletion of an admin-role membership row while other members remain in the org and the handoff is the only sanctioned way to change admins in that case. Allowed when the admin is the org''s only member like deleting a solo Free account.';

DROP TRIGGER IF EXISTS memberships_prevent_admin_delete ON memberships;
CREATE TRIGGER memberships_prevent_admin_delete
  BEFORE DELETE ON memberships
  FOR EACH ROW EXECUTE FUNCTION prevent_admin_membership_delete();

CREATE OR REPLACE FUNCTION restrict_memberships_update_columns() RETURNS trigger
LANGUAGE plpgsql
AS $$
  BEGIN
    IF new.user_id <> old.user_id OR new.organization_id <> old.organization_id THEN
      RAISE EXCEPTION 'Only the role column of a membership row may be updated';
    END IF;
    RETURN new;
  END;
$$;

COMMENT ON FUNCTION restrict_memberships_update_columns() IS 'Defense-in-depth: a membership row''s user_id and organization_id may never change after creation — only role may.';

DROP TRIGGER IF EXISTS memberships_restrict_update ON memberships;
CREATE TRIGGER memberships_restrict_update
  BEFORE UPDATE ON memberships
  FOR EACH ROW EXECUTE FUNCTION restrict_memberships_update_columns();


