CREATE TABLE IF NOT EXISTS organizations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  plan text NOT NULL DEFAULT 'free',
  join_code text UNIQUE NOT NULL DEFAULT substr(md5(random()::text), 1, 8),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  stripe_customer_id text,
  stripe_subscription_id text,
  limit_overrides jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE organizations IS 'One row per customer organization, including a Free-tier "org of one" created automatically at signup.';
COMMENT ON COLUMN organizations.join_code IS 'Regenerable code used to join as a Member. The previous code stops working the instant regenerate_join_code() runs.';
COMMENT ON COLUMN organizations.limit_overrides IS 'Superadmin per-org overrides of the plans defaults, keyed by the same limit column names as plans.';

CREATE TABLE IF NOT EXISTS memberships (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  role organization_role NOT NULL DEFAULT 'member',
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, organization_id)
);

COMMENT ON TABLE memberships IS 'Join table: which user belongs to which organization, and in what role. Exactly one admin row must exist per organization at all times.';

CREATE TABLE IF NOT EXISTS platform_admins (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE
);

COMMENT ON TABLE platform_admins IS 'Superadmins: platform operators who are not members of any customer organization. A row''s existence is what is_platform_admin() checks.';

CREATE TABLE IF NOT EXISTS role_permissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role organization_role NOT NULL,
  permission app_permission NOT NULL,
  UNIQUE (role, permission)
);

COMMENT ON TABLE role_permissions IS 'Static role -> permission mapping. Read-only at runtime — changed only by a future migration or a Superadmin override.';

CREATE TABLE IF NOT EXISTS plans (
  tier text PRIMARY KEY,
  price_cents integer NOT NULL DEFAULT 0,
  max_members integer,
  max_minutes_per_session integer,
  team_session_limit integer,
  solo_session_limit_per_member integer,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES auth.users(id)
);

COMMENT ON TABLE plans IS 'Canonical, Superadmin-editable tier definitions. organizations.plan looks up its default limits here; organizations.limit_overrides supersedes these per-org, per-field, when set.';

CREATE TABLE IF NOT EXISTS organization_invites (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  email text NOT NULL,
  role organization_role NOT NULL DEFAULT 'member' CHECK (role <> 'admin'),
  invited_by uuid NOT NULL REFERENCES auth.users(id),
  token text UNIQUE NOT NULL DEFAULT encode(gen_random_bytes(24), 'hex'),
  status text NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT (now() + INTERVAL '7 days')
);

COMMENT ON TABLE organization_invites IS 'Pending email invitations. role can never be admin — the only way to become Admin is the handoff, never an invite.';


-- ============================================================================
-- R L S:  H E L P E R  F U N C T I O N S
-- ============================================================================

CREATE OR REPLACE FUNCTION is_platform_admin() RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (SELECT 1 FROM platform_admins WHERE user_id = auth.uid());
$$;

COMMENT ON FUNCTION is_platform_admin() IS 'True if the current user is a Superadmin — a row exists for them in platform_admins.';

CREATE OR REPLACE FUNCTION is_organization_member(check_organization_id uuid) RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM memberships
    WHERE organization_id = check_organization_id
      AND user_id = auth.uid()
  );
$$;

COMMENT ON FUNCTION is_organization_member(uuid) IS 'True if the current user belongs to the given organization, in any role.';

CREATE OR REPLACE FUNCTION has_role(check_organization_id uuid, exact_role organization_role) RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM memberships
    WHERE organization_id = check_organization_id
      AND user_id = auth.uid()
      AND role = exact_role
  );
$$;

COMMENT ON FUNCTION has_role(uuid, organization_role) IS 'True if the current user holds exactly the given role in the given organization. Reserved for role-identity checks — feature gating use has_permission().';

CREATE OR REPLACE FUNCTION has_permission(check_organization_id uuid, permission app_permission) RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
      FROM memberships m
      JOIN role_permissions rp ON rp.role = m.role
      WHERE m.organization_id = check_organization_id
        AND m.user_id = auth.uid()
        -- Qualified as has_permission.permission (not a bare `permission`) because
        -- the parameter name collides with the rp.permission column in this query.
        -- PostgreSQL resolves an unqualified name to the column when both are in
        -- scope, so a bare `permission` here would silently compare rp.permission
        -- to itself and always return true — this qualification is what makes the
        -- check actually compare against the caller's requested permission.
        AND rp.permission = has_permission.permission
  );
$$;

COMMENT ON FUNCTION has_permission(uuid, app_permission) IS 'True if the current user''s role in the given organization is seeded, via role_permissions, with the given permission. The primary authorization check for RLS policies and RPCs.';


